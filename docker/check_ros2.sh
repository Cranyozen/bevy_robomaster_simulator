#!/usr/bin/env bash
# check_ros2.sh — type-check / test the `ros2` feature without a full image build.
#
# WHY THIS EXISTS
#   `src/ros2/` is behind `#[cfg(feature = "ros2")]`, so a host `cargo check`
#   never looks at it — and r2r's build script hard-panics without a sourced
#   ROS 2 ("Source your ROS!") plus a colcon-built `rm_interfaces`. The only
#   in-repo way to compile that feature used to be the 13-minute
#   `docker build --target runtime`, which turns a one-line edit into a coffee
#   break.
#
#   This reuses the Dockerfile's own `chef` stage — ROS 2 Jazzy + the Rust
#   toolchain + a warmed dependency cache — mounts the working tree into it, and
#   keeps the cargo target dir and the colcon workspace in named volumes so the
#   second run is incremental.
#
# USAGE
#   docker/check_ros2.sh check          # cargo check --features ros2  (default)
#   docker/check_ros2.sh test           # cargo test  --features ros2
#   docker/check_ros2.sh check --release
#   FEATURES=ros2,bench docker/check_ros2.sh check
#   FORCE_COLCON=1 FEATURES=ros2,bench docker/check_ros2.sh check
#
# ENV
#   FEATURES       cargo feature set (default `ros2`). The benchmark build is
#                  `ros2,bench`; `bench` implies `ros2`.
#   FORCE_COLCON=1 wipe and rebuild the colcon workspace even though it is
#                  already installed. Required after adding/editing a
#                  `.msg`/`.srv`: r2r's bindings are generated by the build
#                  script from the *installed* IDL, so a stale
#                  `/ros2_ws/install` silently compiles against the old message
#                  set with no error at all.
#   CARGO_REGISTRY_VOLUME
#                  named volume for `/usr/local/cargo/registry` (default
#                  `daedalus-check-cargo-registry`). Set it empty to go back to
#                  fetching the crates.io index inside each throwaway container.
#
# The first run compiles the whole dependency graph in the dev profile (several
# minutes); later runs only rebuild the crates this workspace owns, so they take
# seconds. Nothing here writes to the host tree.
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
IMAGE="${IMAGE:-daedalus-chef}"
TARGET_VOLUME="${TARGET_VOLUME:-daedalus-check-target}"
ROS_WS_VOLUME="${ROS_WS_VOLUME:-daedalus-check-ros2ws}"
# CARGO_HOME lives in the image, not in a volume, so every run revalidated the
# crates.io sparse index over the network -- and a flaky link turned a pure
# type-check into `error: failed to load source for dependency 'objc2-app-kit'
# ... unable to update registry 'crates-io'`. Persist just the registry
# subdirectory: `bin/` and `env/` stay the image's, the index and the unpacked
# sources survive between runs, and cargo still fetches anything new on demand.
CARGO_REGISTRY_VOLUME="${CARGO_REGISTRY_VOLUME-daedalus-check-cargo-registry}"
FEATURES="${FEATURES:-ros2}"
FORCE_COLCON="${FORCE_COLCON:-0}"

# ROS 2 / r2r environment, mirroring the `builder` stage of the Dockerfile. The
# two IDL variables are the hard allowlist that keeps bindgen from walking every
# message package in the base image (see docker/ros_idl_packages.py).
read -r -d '' INNER <<'EOS' || true
set -euo pipefail

# ros_env.sh is *sourced*, and a sourced script given no arguments sees the
# caller's positional parameters — so our cargo arguments would be interpreted
# as setup files. Park them first.
cargo_args=("$@")
set --

. /usr/local/bin/ros_env.sh

if [ ! -d /ros2_ws/install/share/rm_interfaces ] || [ "${FORCE_COLCON}" = "1" ]; then
    if [ "${FORCE_COLCON}" = "1" ]; then
        echo "=== colcon build rm_interfaces (FORCE_COLCON=1: rebuilding IDL) ==="
        rm -rf /ros2_ws/build /ros2_ws/install /ros2_ws/log
        # ...and the OTHER half of the same problem, which bites in two crates:
        # `r2r_msg_gen` (build script) and `r2r` (build script) both cache what
        # they generate under `OUT_DIR/<sha256 of the watched environment vars>`,
        # and that hash covers only AMENT_PREFIX_PATH, CMAKE_IDL_PACKAGES,
        # IDL_PACKAGE_FILTER and ROS_DISTRO — never the `.msg`/`.srv` files
        # themselves. A rebuilt colcon install therefore leaves both caches
        # looking perfectly fresh: the new types either do not exist
        # (`error[E0432]: no `SimEvent` in ...`) or the generator panics with
        # `code generation error: rm_interfaces__msg__SimArmorState` because its
        # introspection table predates the message. Drop the cached output of
        # both so they regenerate. `r2r_rcl`/`r2r_common` are left alone: they
        # are IDL-independent and rebinding the rcl C API is the slow part.
        echo "=== dropping cached r2r bindings (they hash env, not IDL) ==="
        rm -rf /target/debug/build/r2r-* \
               /target/debug/build/r2r_msg_gen-* \
               /target/debug/build/r2r_actions-* \
               /target/debug/.fingerprint/r2r-* \
               /target/debug/.fingerprint/r2r_msg_gen-* \
               /target/debug/.fingerprint/r2r_actions-*
    else
        echo "=== colcon build rm_interfaces (first run only) ==="
    fi
    mkdir -p /ros2_ws/src
    rm -rf /ros2_ws/src/rm_interfaces
    cp -r /app/rm_interfaces /ros2_ws/src/rm_interfaces
    cd /ros2_ws
    colcon build --merge-install --cmake-args -DCMAKE_BUILD_TYPE=Release \
        --event-handlers console_cohesion+
fi

. /usr/local/bin/ros_env.sh /opt/ros/"${ROS_DISTRO}"/setup.bash /ros2_ws/install/setup.bash
export IDL_PACKAGE_FILTER="geometry_msgs;sensor_msgs;std_msgs;visualization_msgs;tf2_msgs;rm_interfaces;rcl_interfaces;builtin_interfaces;action_msgs;unique_identifier_msgs"
# NOTE: /usr/local/bin/ros_idl_packages.py is COPYed in the *builder* stage, so
# it does not exist in the chef image. The mounted working tree has it, and
# `export X="$(...)"` does not fail loudly under `set -e` -- it silently leaves
# the allowlist empty, which makes r2r_msg_gen emit a broken action_bindings.rs.
if [ ! -f /usr/local/bin/ros_idl_packages.py ]; then
    cp /app/docker/ros_idl_packages.py /usr/local/bin/ros_idl_packages.py
fi
export CMAKE_IDL_PACKAGES="$(python3 /usr/local/bin/ros_idl_packages.py)"
echo "CMAKE_IDL_PACKAGES=$(echo "${CMAKE_IDL_PACKAGES}" | tr ' ' '\n' | wc -l) package dirs"

cd /app
echo "=== cargo ${cargo_args[*]} --locked --features ${FEATURES} ==="
CARGO_TARGET_DIR=/target cargo "${cargo_args[@]}" --locked --features "${FEATURES}"
EOS

if ! docker image inspect "$IMAGE" >/dev/null 2>&1; then
    echo "=== building the $IMAGE image (Dockerfile target: chef) ==="
    docker build --target chef -t "$IMAGE" "$REPO"
fi

CARGO_ARGS=("$@")
if [ "${#CARGO_ARGS[@]}" -eq 0 ]; then
    CARGO_ARGS=(check)
fi

CARGO_VOLUME_ARGS=()
if [ -n "${CARGO_REGISTRY_VOLUME}" ]; then
    CARGO_VOLUME_ARGS=(-v "$CARGO_REGISTRY_VOLUME":/usr/local/cargo/registry)
fi

exec docker run --rm \
    -v "$REPO":/app \
    -v "$TARGET_VOLUME":/target \
    -v "$ROS_WS_VOLUME":/ros2_ws \
    "${CARGO_VOLUME_ARGS[@]}" \
    -e FEATURES="$FEATURES" \
    -e FORCE_COLCON="$FORCE_COLCON" \
    "$IMAGE" \
    bash -c "$INNER" -- "${CARGO_ARGS[@]}"
